try:
    x1 = int(input("Введите x1: "))
    y1 = int(input("Введите y1: "))
    x2 = int(input("Введите x2: "))
    y2 = int(input("Введите y2: "))

    a = abs(x2-x1)   
    b = abs(y2-y1)  

    P = 2*(a+b)    
    S = a*b         

    print(f"Периметр прямоугольника будет равен {P} \n Площадь прямоугольника юужет равна {S}")

except:
    print("Ошибка: Число некоректное")